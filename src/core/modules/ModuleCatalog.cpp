Module setting(char const* id, char const* name, char const* desc, char const* key,
               char const* group, S section, bool defaultOn, char const* parent = kNone) {
    return {id, name, desc, key, parent, group, section, B::Setting, defaultOn};
}

Module saved(char const* id, char const* name, char const* desc, char const* key,
             char const* group, S section, bool defaultOn, char const* parent = kNone) {
    return {id, name, desc, key, parent, group, section, B::Saved, defaultOn};
}

Module custom(char const* id, char const* name, char const* desc, char const* group,
              S section, bool defaultOn, char const* parent = kNone) {
    return {id, name, desc, kNone, parent, group, section, B::Custom, defaultOn};
}

Module infoMod(char const* id, char const* name, char const* desc, char const* key,
               char const* group, bool defaultOn, char const* parent = kInfoSuite) {
    return {id, name, desc, key, parent, group, S::Info, B::Setting, defaultOn};
}

